def _read_map(gen: Path) -> dict[str, str]:
    try:
        raw = json.loads((gen / MAP_NAME).read_text(encoding="utf-8"))
        return {str(k): str(v) for k, v in raw.items() if isinstance(k, str) and isinstance(v, str)}
    except (OSError, ValueError):
        return {}


def _list_modules(gen: Path) -> list[Path]:
    if not gen.exists():
        return []
    return sorted(
        p for p in gen.glob("*.tsx")
        if p.name != REGISTRY_NAME and _SAFE_STEM.match(p.stem) and p.is_file()
    )


def sync_scene_registry(composer: Path, live_slugs: set[str] | None = None) -> dict:
    """扫描 src/generated/*.tsx,重写 registry.ts(静态 import)。

    live_slugs 给定时顺带清理已删除项目的产物——项目删掉后,
    残留的 .tsx 会把一个不存在的 slug 注册进 Root,渲染时才炸。
    """
    gen = generated_dir(composer)
    gen.mkdir(parents=True, exist_ok=True)
    mapping = _read_map(gen)
    modules = _list_modules(gen)
    removed: list[str] = []
    if live_slugs is not None:
        keep: list[Path] = []
        for p in modules:
            slug = mapping.get(p.stem, p.stem)
            if slug in live_slugs:
                keep.append(p)
            else:
                p.unlink(missing_ok=True)
                removed.append(slug)
                mapping.pop(p.stem, None)
        modules = keep

    lines = [
        "// AUTO-GENERATED by tools/motion_design/scene_contract.py — don't edit.",
        "// 每条都是模型为该项目写的专属画面;没有对应项目的条目会被清掉。",
    ]
    for i, p in enumerate(modules):
        lines.append(f'import * as m{i} from "./{p.stem}";')
    lines.append("")
    lines.append("export const SCENE_MODULES: Record<string, unknown> = {")
    for i, p in enumerate(modules):
        slug = mapping.get(p.stem, p.stem)
        if scene_filename(slug) != p.stem:
            mapping[p.stem] = slug
        lines.append(f"  {json.dumps(slug, ensure_ascii=False)}: m{i}.default,")
        if sanitize_identifier(slug) != p.stem:
            lines.append(f"  // {p.stem}.tsx ← {slug}(文件名已清洗,别名见 scene_map.json)")
    lines.append("};")
    lines.append("")
    (gen / REGISTRY_NAME).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (gen / MAP_NAME).write_text(
        json.dumps(mapping, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    return {"modules": [mapping.get(p.stem, p.stem) for p in modules], "removed": removed}


