def scene_filename(slug: str) -> str:
    """项目 slug → src/generated 里的文件名(不含扩展名)。

    slug 已经是 [0-9a-z-],正常情况原样返回。只做防御性清洗,
    绝不接受路径分隔符——否则模型产物可以写到目录外面。
    """
    safe = re.sub(r"[^0-9A-Za-z_-]+", "-", (slug or "").strip()).strip("-")
    if not safe or not _SAFE_STEM.match(safe):
        safe = ("scene-" + safe).strip("-") or "scene"
    return safe


def sanitize_identifier(slug: str) -> str:
    """slug → 合法的 TS 标识符([A-Za-z0-9_]);首字符不能是数字。"""
    ident = re.sub(r"[^0-9A-Za-z_]+", "_", (slug or "").strip()).strip("_")
    if not ident:
        ident = "scene"
    if ident[0].isdigit():
        ident = "s_" + ident
    return ident


def generated_dir(composer: Path) -> Path:
    return Path(composer) / GENERATED_DIR


# ────────────────────────────── 逐拍文件命名 ──────────────────────────────
# 每拍的组件单独一个文件:`<slug>.beat-<id>.tsx`。
# 名字里带点,所以不会被 _list_modules 当成一个独立项目注册成组合
# (它要求 stem 匹配 ^[A-Za-z0-9][A-Za-z0-9_-]*$,点不合法)。
BEAT_MARK = ".beat-"


def beat_stem(slug: str, beat_id: str) -> str:
    safe = re.sub(r"[^0-9A-Za-z_-]+", "-", (beat_id or "").strip()).strip("-") or "beat"
    return f"{scene_filename(slug)}{BEAT_MARK}{safe}"


def beat_paths(composer: Path, slug: str) -> list[Path]:
    gen = generated_dir(composer)
    if not gen.exists():
        return []
    prefix = scene_filename(slug) + BEAT_MARK
    return sorted(p for p in gen.glob("*.tsx") if p.stem.startswith(prefix))


def build_scene_aggregator(slug: str, beats: list[dict], components: list[str],
                           *, width: int, height: int) -> str:
    """把每拍的组件拼成一个 Scene:按 props.beat.id 分发。

    聚合文件由我们生成(不是模型写的),所以它可以直接 import 兄弟文件;
    模型写的单拍组件只允许 import react/remotion。
    最后一档兜底会画这一拍自己的标题 —— 保证任何情况下都不会白屏。
    """
    q = chr(39)  # 生成出来的 JS 统一用单引号,Python 这边就不用转义了
    out: list[str] = [
        "// AUTO-GENERATED by film.py scene — 每拍一个组件,这里只做分发。",
        "import React from " + q + "react" + q + ";",
    ]
    for i, comp in enumerate(components):
        out.append("import * as m" + str(i) + " from " + q + "./" + comp + q + ";")
    out += [
        "",
        "const W = " + str(int(width)) + ";",
        "const H = " + str(int(height)) + ";",
        "",
        "/** 兜底:至少把这一拍自己的标题画出来,不会白屏。 */",
        "const Fallback: React.FC<any> = ({ beat, t, palette }: any) => {",
        "  const c = palette || {};",
        "  const title: string[] = Array.isArray(beat && beat.title) ? beat.title : [String((beat && beat.title) || '')];",
        "  const k = W / 1080;",
        "  const grow = 1 + Math.sin(t * 1.8) * 0.012;",
        "  return (",
        "    <div style={{ position: 'absolute', inset: 0, overflow: 'hidden', background: c.canvas || '#E8EDF0' }}>",
        "      <div style={{ position: 'absolute', left: 70 * k, right: 60 * k, top: H * 0.22, transform: `scale(${grow})`, transformOrigin: 'left top' }}>",
        "        {title.filter(Boolean).map((line: string, i: number) => (",
        "          <div key={i} style={{ fontWeight: 900, fontSize: (i ? 78 : 96) * k, lineHeight: 1.12, marginBottom: 18, color: i ? (c.red || '#F04438') : (c.ink || '#172838') }}>{line}</div>",
        "        ))}",
        "      </div>",
        "      <div style={{ position: 'absolute', left: 70 * k, top: H * 0.62, height: 14, width: W * 0.5 * (0.6 + 0.4 * Math.abs(Math.sin(t * 1.4))), background: c.red || '#F04438' }} />",
        "      {beat && beat.big ? <div style={{ position: 'absolute', left: 70 * k, top: H * 0.72, fontWeight: 900, fontSize: 110 * k, color: c.red || '#F04438' }}>{beat.big}</div> : null}",
        "    </div>",
        "  );",
        "};",
        "",
        "export default function Scene(props: { beat: any; t: number; palette: Record<string, string>; width: number; height: number }) {",
        "  const id = props.beat ? props.beat.id : undefined;",
    ]
    for i, b in enumerate(beats):
        bid = repr(str(b.get("id") or ""))
        out.append("  if (id === " + bid + ") return React.createElement(m" + str(i) + ".default, props);")
    out += [
        "  return React.createElement(Fallback, props);",
        "}",
        "",
    ]
    return chr(10).join(out)


def write_scene_aggregator(composer: Path, slug: str, beats: list[dict], components: list[str],
                           *, width: int, height: int) -> Path:
    target = generated_dir(composer) / f"{scene_filename(slug)}.tsx"
    target.write_text(build_scene_aggregator(slug, beats, components, width=width, height=height),
                      encoding="utf-8", newline=chr(10))
    return target


# ────────────────────────────── 注释剥离 ──────────────────────────────
def strip_comments(src: str) -> str:
    """去掉 // 与 /* */ 注释,保留字符串字面量。

    契约要求「外链只在注释里出现」不算违规,所以禁用项要按去注释后的
    代码判断;而字符串里的 URL 仍然算违规,因此字符串内容原样保留。
    """
    out: list[str] = []
    i, n = 0, len(src)
    state = "code"
    while i < n:
        ch = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if state == "code":
            if ch == "/" and nxt == "/":
                state = "line"
                i += 2
                continue
            if ch == "/" and nxt == "*":
                state = "block"
                i += 2
                continue
            if ch == '"':
                state = "dq"
            elif ch == "'":
                state = "sq"
            elif ch == "`":
                state = "tpl"
            out.append(ch)
            i += 1
        elif state == "line":
            if ch == "\n":
                state = "code"
                out.append(ch)
            i += 1
        elif state == "block":
            if ch == "*" and nxt == "/":
                state = "code"
                i += 2
                continue
            out.append("\n" if ch == "\n" else " ")
            i += 1
        else:
            out.append(ch)
            if ch == "\\" and i + 1 < n:
                out.append(src[i + 1])
                i += 2
                continue
            if (state == "dq" and ch == '"') or (state == "sq" and ch == "'") or (
                state == "tpl" and ch == "`"
            ):
                state = "code"
            i += 1
    return "".join(out)


# ────────────────────────────── 本地校验 ──────────────────────────────
FORBIDDEN: tuple[tuple[str, str], ...] = (
    ("require(", "禁止 require(...):只能 import React"),
    ("eval(", "禁止 eval(...)"),
    ("dangerouslySetInnerHTML", "禁止 dangerouslySetInnerHTML"),
    ("Math.random", "禁止 Math.random:画面必须可复现"),
    ("Date.now", "禁止 Date.now:画面必须可复现"),
    ("<script", "禁止 <script"),
    ("process.", "禁止访问 process.*"),
    ("globalThis", "禁止 globalThis"),
)

# 模型偶尔把「画个网页」当任务,整篇返回 HTML 文档。tsx 语法检查能拦住,
# 但报错难懂;这里先给出直白的中文原因,重试提示才改得动。
_HTML_DOC_RE = re.compile(r"(?i)<!doctype\s+html|<html[\s>]|<head[\s>]|<body[\s>]")

# 顶层 await / async 组件:只能做同步渲染,否则 Remotion 逐帧渲染会挂。
_TOP_AWAIT_RE = re.compile(r"(?m)^(?:await\b|export\s+default\s+async\b)")

_IMPORT_RE = re.compile(r"""(?m)^\s*import\s+(?:[^;'"]*?\s+from\s+)?['"]([^'"]+)['"]""")

# SVG 的命名空间是标识符,不是网络地址:xmlns="http://www.w3.org/2000/svg" 不会发请求。
# 模型写内联 SVG 时几乎一定会带它,按外链拒绝等于把所有正常画面挡在门外。
_XMLNS_RE = re.compile(r"""xmlns(?::[\w-]+)?\s*=\s*["']https?://[^"']*["']""")
_SVG_NS_RE = re.compile(r"""["']https?://www\.w3\.org/[^"']*["']""")


def _strip_svg_namespaces(code: str) -> str:
    code = _XMLNS_RE.sub("", code)
    return _SVG_NS_RE.sub('""', code)


def validate_scene_source(src: str, beat_ids: list[str] | None = None,
                          beat_kinds: dict[str, str] | None = None) -> tuple[bool, str]:
    """返回 (是否可用, 中文原因)。全部本地判断,不联网。

    beat_ids 给定时额外检查:每一拍的分支里都必须有时间变化量,
    否则那一拍在成片里就是一张定格图(评审判死场)。
    """
    if not isinstance(src, str) or not src.strip():
        return False, "模型没有返回内容"
    size = len(src.encode("utf-8"))
    if size > MAX_SCENE_BYTES:
        return False, f"文件过大:{size} 字节,上限 {MAX_SCENE_BYTES} 字节"
    code = strip_comments(src)
    if _HTML_DOC_RE.search(code):
        return False, ("这是一整篇 HTML 网页(<!DOCTYPE html>/<html>/<style>),"
                       "不是 Remotion 组件。只要一个 TSX:import React + export default function Scene")
    if "export default" not in code:
        return False, "缺少 export default:解析不到默认导出的 Scene 组件"
    imports = _IMPORT_RE.findall(code)
    if not imports:
        return False, '缺少 import React from "react"'
    bad = [s for s in imports if s not in ("react", "react/jsx-runtime", "remotion")]
    if bad:
        return False, "禁止 import 其他模块:" + ", ".join(sorted(set(bad)))
    if re.search(r"https?://", _strip_svg_namespaces(code)):
        return False, "禁止外链(http:// / https://):画面只能用内联 SVG/形状/文字"
    for token, reason in FORBIDDEN:
        if token in code:
            return False, reason
    if _TOP_AWAIT_RE.search(code):
        return False, "禁止顶层 await / async 默认导出:组件必须是同步函数"
    if beat_ids:
        # 组件必须由 props.beat 决定画哪一拍。模型另一种常见写法是自己按
        # useCurrentFrame/durationInFrames 切成 5 段 —— 那样会和真实配音时间轴
        # 错位(每拍 7~10 秒不等,它却按均分切),必须拒绝。
        if not re.search(r"\bprops\s*\.\s*beat\b|\{\s*beat\b", code):
            return False, ("组件没有用 props.beat:它在自己按帧数切片。"
                           "Scene 只负责画 props.beat 指定的那一拍,不要自己排时间轴")
        drawn = set(_BRANCH_RE.findall(code)) | beat_mentions(code, beat_ids)
        missing = [b for b in beat_ids if b not in drawn]
        # 另一种合法写法是**按镜头类型**分支(beat.kind === "flow"),
        # 而不是按 id。它同样保证每一拍都有自己的画面(只是同类共用一幅),
        # 不该因为写法不同就整版丢掉 —— 一次生成要七分钟,丢不起。
        if missing and beat_kinds:
            kinds_drawn = set(_KIND_BRANCH_RE.findall(code))
            missing = [b for b in missing if beat_kinds.get(b) not in kinds_drawn]
        # 末尾那个 `return (...)` 是兜底分支:它拿 props.beat 的数据画最后一拍是
        # 合法写法(收尾拍通常就是"标题 + 一句话")。所以只差最后一拍时放行;
        # 差得多就说明它真的只画了开头,还得退回模板。
        if missing == [beat_ids[-1]]:
            last_branch = max((m.end() for m in _BRANCH_RE.finditer(code)), default=0)
            last_kind = max((m.end() for m in _KIND_BRANCH_RE.finditer(code)), default=0)
            tail = code[max(last_branch, last_kind):]
            if _FALLBACK_RE.search(tail):
                missing = []
        if missing:
            return False, "这些拍没有自己的画面分支:" + ", ".join(missing)
        # 只拦「整份文件一次都不动」——那是一张海报,不是能播的画面。
        # 个别拍偏静由 SceneFilm 的兜底微动兜住,不因此丢掉整套好画面。
        if not any(h in code for h in _MOTION_HINTS):
            return False, ("整个组件没有任何随时间变化的画面(会形成死场)。"
                           "至少用 props.t 做一处持续运动(位移/呼吸/扫光/循环)")
    return True, ""


def extract_tsx(text: str) -> str:
    """从模型回复里取出 TSX:优先 ```tsx 代码块,其次 ```,最后原文。

    有些网关会在正文后面追加 <tool_call> / ｜｜DSML｜｜ 之类的私有标记;
    它们不是源码,留在文件里会直接让 esbuild 报错,所以先剥掉。
    """
    if not isinstance(text, str):
        return ""
    m = re.search(r"```(?:tsx|ts|jsx|javascript|js)?\s*\n(.*?)```", text, re.S)
    src = m.group(1) if m else text
    src = re.split(r"</\s*\|+[^>]*\|+?>", src)[0]
    src = re.split(r"<\|+[^>]*\|+>", src)[0]
    src = re.split(r"(?m)^\s*</?(?:tool_call|function_call|invoke|parameter)\b", src)[0]
    return src.strip()


# ────────────────────────────── 逐拍运动检查 ──────────────────────────────
# 真实事故:模型给 point1 那一拍画了静态表格,整段 4 秒画面完全不动,
# 评审判死场,观众在这里划走。语法检查管不了这件事,所以单独加一道。
_BRANCH_RE = re.compile(r"""beat\s*\.\s*id\s*===?\s*["']([^"']+)["']""")
# 按镜头类型分支:beat.kind / b.kind / props.beat.kind === "flow"
_KIND_BRANCH_RE = re.compile(r"""\.kind\s*===?\s*["']([^"']+)["']""")
# 兜底分支:最后一次分支之后还剩下的 return,并且用了这一拍自己的字段。
# 模型常把 props.beat 先存成 `const b = props.beat`,所以不能只认 `beat.`。
_FALLBACK_RE = re.compile(
    r"return[\s\S]{0,500}?(?:beat\s*\.|b\s*\.\s*(?:title|stamp|big|bigSub|items|left|right|lines|statement|steps|note|kind))"
)
# 任何会随 t 变化的写法都算运动(直接差值、正弦、取模循环、插值函数)。
_MOTION_HINTS = ("props.t", "useCurrentFrame", "Math.sin(", "Math.cos(", "% ", "spring(", "interpolate(")


def beat_mentions(src: str, beat_ids: list[str]) -> set[str]:
    """没走 `beat.id === "x"` 分支,但按 id 组装的实现也算「有这一拍」。

    模型另一种常见写法是 `const scenes = [<Hook/>, <Point1/>]` 配
    `const BEATS = ["hook", ...]`,或者一张 id→组件 的映射表。
    这种实现同样是一拍一幅画面,不该因为写法不同被拒。
    """
    found: set[str] = set()
    for b in beat_ids:
        if re.search(r"""["']""" + re.escape(b) + r"""["']""", src):
            found.add(b)
    return found


def _word(ident: str) -> str:
    return r"\b" + re.escape(ident) + r"\b"


def beat_motion_gaps_by_component(src: str, beat_ids: list[str]) -> list[str]:
    """按「拍 → 组件」的写法逐拍查运动。

    覆盖两种真实写法:
      const scenes = [<Hook/>, <Point1/>]        // 数组按顺序对应 BEATS
      <Hook/> 或 components 里 key 为 hook 的映射
    做法:先找出渲染了哪些组件名,再把这些组件各自函数体切出来查 t。
    """
    # BEATS 数组的顺序决定数组写法的对应关系
    order: list[str] = []
    m = re.search(r"(?:const|let|var)\s+BEATS\s*=\s*\[([^\]]*)\]", src)
    if m:
        order = re.findall(r"""["']([^"']+)["']""", m.group(1))
    if not order:
        order = list(beat_ids)

    # scenes/数组里的组件顺序
    arr = []
    for m in re.finditer(r"\[\s*(<[A-Z][\w]*\s*/>[\s\S]*?)\]\s*;", src):
        arr = re.findall(r"<([A-Z][\w]*)\s*/>", m.group(1))
        if arr:
            break
    mapping: dict[str, str] = {}
    if len(arr) == len(order):
        mapping = dict(zip(order, arr))

    def body_of(comp: str) -> str:
        # 组件可能写成 const X = (...) => (...)；也可能 function X(...) {...}
        m = re.search(r"(?:const|let)\s+" + _word(comp) + r"\s*(?::[^=]+)?=\s*", src)
        if m:
            start = m.end()
            # 从赋值开头取到该组件下一个顶层声明之前
            nxt = re.search(r"(?m)^(?:const|let|var|function|export)\s", src[start:])
            return src[start:start + nxt.start()] if nxt else src[start:]
        m = re.search(r"function\s+" + _word(comp) + r"\s*\(", src)
        if m:
            tail = src[m.end():]
            nxt = re.search(r"(?m)^(?:const|let|var|function|export)\s", tail)
            return tail[:nxt.start()] if nxt else tail[:4000]
        return ""

    gaps = []
    for beat, comp in mapping.items():
        body = body_of(comp)
        if not body:
            continue
        if not any(h in body for h in _MOTION_HINTS):
            gaps.append(beat)
    return gaps


def motion_gaps(src: str) -> list[str]:
    """返回「这一拍里一次都没用 t」的 beat id 列表(可能为空)。

    以 `beat.id === "x"` 为界把源码切开,逐段看有没有随时间变化的表达式。
    这是启发式检查:它不判断动得好不好看,只拦「整段完全静止」这种硬伤。
    """
    if not isinstance(src, str):
        return []
    marks = list(_BRANCH_RE.finditer(src))
    if not marks:
        return []
    # 模型常把时间先落到一个局部变量上(`const p = props.t;`),分支里再用 p。
    # 这类变量要跟着算运动,否则会把好画面误判成静止。
    animated = {
        m.group(1)
        for m in re.finditer(r"(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=[^;\n]*", src)
        if any(h in m.group(0) for h in _MOTION_HINTS)
    }
    gaps: list[str] = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(src)
        body = src[m.end():end]
        # 最后一段会延伸进兜底 else 分支,把它切掉,别让兜底的运动替这一拍顶包。
        if i + 1 == len(marks):
            tail = re.search(r"\}\s*else\s*\{", body)
            if tail:
                body = body[:tail.start()]
        moving = any(h in body for h in _MOTION_HINTS) or any(
            re.search(r"\b" + re.escape(name) + r"\b", body) for name in animated
        )
        if not moving:
            gaps.append(m.group(1))
    return gaps



