def validate_beat_source(src: str, beat: dict) -> tuple[bool, str]:
    """单拍组件校验。不要求分支,只要求:合法 TSX、有运动、画的是这一拍。"""
    if not isinstance(src, str) or not src.strip():
        return False, "模型没有返回内容"
    size = len(src.encode("utf-8"))
    if size > MAX_BEAT_BYTES:
        return False, f"文件过大:{size} 字节,上限 {MAX_BEAT_BYTES} 字节"
    code = strip_comments(src)
    if _HTML_DOC_RE.search(code):
        return False, "这是一整篇 HTML 网页,不是 Remotion 组件"
    if "export default" not in code:
        return False, "缺少 export default"
    imports = _IMPORT_RE.findall(code)
    if not imports:
        return False, '缺少 import React from "react"'
    bad = [s for s in imports if s not in ("react", "react/jsx-runtime", "remotion")]
    if bad:
        return False, "禁止 import 其他模块:" + ", ".join(sorted(set(bad)))
    if re.search(r"https?://", _strip_svg_namespaces(code)):
        return False, "禁止外链:画面只能用内联 SVG/形状/文字"
    for token, reason in FORBIDDEN:
        if token in code:
            return False, reason
    if _TOP_AWAIT_RE.search(code):
        return False, "禁止顶层 await / async 默认导出"
    if "useCurrentFrame" in code or "durationInFrames" in code:
        return False, "不要自己取帧:用 props.t 做这一拍内的动画"
    # 必须真的在动。注意:`const t = props.t;` 这种"取出来不用"不算运动,
    # 先把这类纯声明剥掉,再看剩下的代码里有没有真正的时变表达式。
    moving_code = re.sub(r"(?:const|let|var)\s+[A-Za-z_$][\w$]*\s*=\s*props\.t\s*;", "", code)
    if not any(h in moving_code for h in _MOTION_HINTS):
        return False, "没有任何随时间变化的画面(props.t 一次都没用),这一拍会变成静止图"
    # 必须画这一拍自己的内容:要么读 beat 的字段,要么把这一拍的文字写进去了
    reads_beat = re.search(r"\b(?:b|beat|props\.beat)\s*\.\s*(?:" + "|".join(_BEAT_FIELDS) + r")\b", code)
    literals = []
    for key in ("big", "bigSub", "stamp", "statement", "note"):
        v = beat.get(key)
        if isinstance(v, str) and len(v.strip()) >= 2:
            literals.append(v.strip())
    for key in ("title", "lines"):
        v = beat.get(key)
        if isinstance(v, list):
            literals.extend(x.strip() for x in v if isinstance(x, str) and len(x.strip()) >= 2)
    wrote_text = any(lit in code for lit in literals)
    if not (reads_beat or wrote_text):
        return False, "画面没有用到这一拍自己的内容(既没读 beat 字段,也没把这一拍的文字画上去)"
    return True, ""


def build_scene_prompt(
    film: dict,
    meta: dict,
    *,
    width: int,
    height: int,
) -> tuple[str, str]:
    """返回 (system, user)。user 是紧凑 JSON,含全部节拍和配色。"""
    palette = dict(DEFAULT_PALETTE)
    palette.update({k: v for k, v in (film.get("theme") or {}).items() if isinstance(v, str)})
    beats = []
    for b in film.get("beats") or []:
        if not isinstance(b, dict):
            continue
        beats.append({k: v for k, v in b.items() if k not in ("visual", "phone", "face")})
    payload = {
        "title": meta.get("title") or meta.get("name") or "",
        "style": meta.get("style") or "",
        "canvas": {"width": width, "height": height},
        "palette": palette,
        "header": film.get("header") or "",
        "footer": (film.get("footer") or {}).get("label") or "",
        "beats": beats,
        "must_cover_beat_ids": [b.get("id") for b in beats if b.get("id")],
        "timing": film.get("timing") or {},
        "reminder": (
            "每个 beat.id 都要有专属画面;具体对象(如人造太阳/血小板/脑电)必须画出来,"
            "不要人物脸/手机/支付这类通用元素。"
        ),
    }
    return SCENE_SYSTEM, json.dumps(payload, ensure_ascii=False)
