_ESBUILD_JS = r"""
const esbuild = require(process.argv[1]);
const fs = require("fs");
const src = fs.readFileSync(process.argv[2], "utf8");
esbuild
  .transform(src, { loader: "tsx", jsx: "automatic", format: "esm", target: "es2020" })
  .then(() => process.stdout.write("SCENE_SYNTAX_OK"))
  .catch((e) => {
    process.stderr.write(String((e && (e.message || e.errors)) || e));
    process.exit(1);
  });
"""


def find_esbuild(composer: Path) -> Path | None:
    env = os.environ.get("OE_ESBUILD", "")
    candidates = [
        Path(env) if env else None,
        Path(composer) / "node_modules" / "esbuild" / "lib" / "main.js",
        Path(composer) / "node_modules" / "esbuild",
    ]
    for c in candidates:
        if c and c.exists():
            return c
    return None


def find_node() -> str:
    node_dir = os.environ.get("OE_NODE_DIR", "")
    if node_dir:
        for name in ("node.exe", "node"):
            p = Path(node_dir) / name
            if p.exists():
                return str(p)
    return "node"


def check_scene_syntax(
    path: Path,
    *,
    composer: Path,
    node: str | None = None,
    esbuild: Path | None = None,
    runner=None,
) -> tuple[bool, str]:
    """用本地 esbuild 做一次 transform;失败返回 (False, 中文原因)。

    runner 可注入(测试里替换真正的子进程),签名
    runner(argv, timeout) -> (returncode, stdout, stderr)。

    校验器本身跑不起来(没装 node/esbuild)时返回 (True, 说明),
    调用方记一条提示但仍采用文件——渲染失败有模板兜底,不必因工具缺失
    把模型写的画面一律丢掉。
    """
    esbuild = esbuild or find_esbuild(composer)
    if esbuild is None:
        return True, "本地没有 esbuild(remotion-composer/node_modules/esbuild),已跳过语法校验"
    argv = [node or find_node(), "-e", _ESBUILD_JS, str(esbuild), str(path)]
    try:
        if runner is not None:
            rc, out, err = runner(argv, 90)
        else:
            proc = subprocess.run(argv, capture_output=True, text=True, timeout=90)
            rc, out, err = proc.returncode, proc.stdout, proc.stderr
    except FileNotFoundError:
        return True, "找不到 node,已跳过语法校验"
    except subprocess.TimeoutExpired:
        return False, "esbuild 语法校验超时"
    if rc == 0 and "SCENE_SYNTAX_OK" in (out or ""):
        return True, ""
    detail = (err or out or "").strip().replace("\r", "")
    # 保留 esbuild 的源码行/列:模型常写出一个小语法错,
    # 只留第一行的话没法判断是提示词问题还是输出截断问题。
    summary = " | ".join(line.strip() for line in detail.splitlines() if line.strip())[:900]
    return False, f"esbuild 语法校验失败:{summary or f'退出码 {rc}'}"


