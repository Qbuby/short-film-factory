"""把 timing.json / subtitles.json 同步进 Remotion,消灭手抄时间轴。

以前每改一次稿,都要手工把 BEATS 的七个秒数抄进 AiBubble.tsx、把总时长抄进
Root.tsx、再手写一份 props.json。漏一个,成片就会「字幕和口播差一拍」。
这里一次生成三个文件,Remotion 侧只 import,不再有第二处真值。

用法:
  python tools/motion_design/sync_remotion_timing.py \
      --project projects/code-first/ai-bubble \
      --ts remotion-composer/src/aiBubbleTiming.ts \
      --props remotion-composer/public/ai-bubble/props.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--ts", required=True, help="生成的 TS 模块路径")
    ap.add_argument("--props", required=True, help="生成的 Remotion props.json 路径")
    ap.add_argument("--name", default="AI_BUBBLE", help="导出常量前缀")
    ap.add_argument("--audio", default="", help="props 里的 audioSrc(相对 remotion public/)")
    args = ap.parse_args()

    proj = Path(args.project).resolve()
    timing = json.loads((proj / "timing.json").read_text(encoding="utf-8"))
    subs = json.loads((proj / "subtitles.json").read_text(encoding="utf-8"))

    gap = float(timing.get("gap", 0.0))
    total = float(timing["total"])

    # 时间轴必须自洽:每拍起点 = 上一拍终点,最后一拍终点 = 总时长。
    # 有绝对 start/end 就直接用 —— 真人朗读的句间留白并不均匀,
    # 靠 dur+gap 累加会一路漂(实测到第四拍就偏了 0.25s)。
    beats: list[tuple[str, float, float]] = []
    if all("start" in s and "end" in s for s in timing["segments"]):
        for seg in timing["segments"]:
            beats.append((seg["id"], round(float(seg["start"]), 3), round(float(seg["end"]), 3)))
        total = beats[-1][2]
        # 真人朗读的句间留白不均匀,段与段之间会有空档。
        # 空档里没有任何一拍是 active 的,画面上就什么都不剩(只剩纸纹)。
        # 让前一拍一直保持到下一拍开始 —— 停顿时停在上一屏,而不是闪成空场。
        beats = [
            (bid, s, (beats[i + 1][1] if i + 1 < len(beats) else e))
            for i, (bid, s, e) in enumerate(beats)
        ]
    else:
        t = 0.0
        for seg in timing["segments"]:
            beats.append((seg["id"], round(t, 3), round(t + float(seg["dur"]) + gap, 3)))
            t += float(seg["dur"]) + gap
        # 收掉累积误差,让尾拍正好等于总时长(否则视频尾部会多/少几帧)
        sid, s0, _ = beats[-1]
        beats[-1] = (sid, s0, round(total, 3))

    body = [
        "// AUTO-GENERATED by tools/motion_design/sync_remotion_timing.py",
        f"// 数据源: {proj.as_posix()}/{{script,timing,subtitles}}.json",
        "// 不要手改 —— 改稿子后重跑 voiceover.py + make_subs.py + 本脚本。",
        "",
        f"export const {args.name}_TOTAL = {total};",
        f"export const {args.name}_BEATS = {{",
    ]
    for bid, a, b in beats:
        body.append(f"  {bid}: [{a}, {b}],")
    body.append("} as const;")
    body.append("")
    body.append(f'export type {args.name.capitalize()}BeatId = keyof typeof {args.name}_BEATS;')
    body.append("")

    # Hook 拍常常装两句话。第二句开始的时刻决定第二个落点(铭牌砸进来的那一下),
    # 从字幕数据里读出来,而不是在 TSX 里拍脑袋写个 2.2 秒。
    first_id, h0, h1 = beats[0]
    split = next((c["start"] for c in subs if h0 < c["start"] < h1), None)
    if split is None:
        split = round(h0 + (h1 - h0) * 0.4, 3)
    body.append(f"// 第一拍里第二句话的起点,用于第二个落点(秒)")
    body.append(f"export const {args.name}_SPLIT = {round(float(split), 3)};")
    body.append("")

    ts_path = Path(args.ts)
    if not ts_path.is_absolute():
        ts_path = Path.cwd() / ts_path
    ts_path.parent.mkdir(parents=True, exist_ok=True)
    ts_path.write_text("\n".join(body), encoding="utf-8", newline="\n")

    # props.json 给 CLI 用;字幕文本与 timing 同源,不会再和音频打架
    props = {"subs": [[c["start"], c["end"], c["text"]] for c in subs]}
    if args.audio:
        props["audioSrc"] = args.audio
    props_path = Path(args.props)
    if not props_path.is_absolute():
        props_path = Path.cwd() / props_path
    props_path.parent.mkdir(parents=True, exist_ok=True)
    props_path.write_text(json.dumps(props, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")

    print(json.dumps({
        "ok": True,
        "total": total,
        "beats": {b[0]: [b[1], b[2]] for b in beats},
        "cues": len(subs),
        "last_cue_end": subs[-1]["end"] if subs else None,
        "ts": str(ts_path),
        "props": str(props_path),
    }, ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())